// Generated says, at the top of each file made from the looks, where it
// comes from. It opens frontend/bundle/looks.css as a CSS comment, so it
// must not hold the comment's end, */: a path glob like looks/*/look.css
// ended the comment early, and the rest of it hid the first rule, the
// Teletype paper's colours.
const Generated = "Generated by go generate from each look's frontend/looks/<folder>/look.css. DO NOT EDIT. See docs/looks.md."

// TS is frontend/src/looks.gen.ts: what the pages need to know about
// each look.
func TS(all []Look) ([]byte, error) {
	type texture struct {
		Label     string `json:"label"`
		Sprockets string `json:"sprockets"`
		Rules     string `json:"rules"`
		Shadows   string `json:"shadows"`
	}
	type look struct {
		ID          string   `json:"id"`
		Name        string   `json:"name"`
		Description string   `json:"description"`
		TextSize    int      `json:"textSize"`
		Texture     *texture `json:"texture"`
	}
	out := make([]look, len(all))
	for i, l := range all {
		out[i] = look{ID: l.ID, Name: l.Name, Description: l.Description, TextSize: l.TextSize}
		if out[i].TextSize == 0 {
			out[i].TextSize = 100
		}
		if t := l.Texture; t != nil {
			out[i].Texture = &texture{t.Label, t.Sprockets, t.Rules, t.Shadows}
		}
	}
	b, err := json.MarshalIndent(out, "", "  ")
	if err != nil {
		return nil, err
	}
	var buf bytes.Buffer
	fmt.Fprintf(&buf, "// %s\n\nimport type { Look } from \"./looks.js\";\n\nexport const generated: Look[] = %s;\n", Generated, b)
	return buf.Bytes(), nil
}

// SiteData is site/data/looks.toml, for the website's looks band and
// its lists of the looks. Hugo reads it as site.Data.looks, with the
// looks as its "looks".
func SiteData(all []Look) ([]byte, error) {
	type look struct {
		ID      string `toml:"id"`
		Name    string `toml:"name"`
		Since   string `toml:"since"`
		Tagline string `toml:"tagline"`
		Hero    *Hero  `toml:"hero,omitempty"`
	}
	out := make([]look, len(all))
	for i, l := range all {
		out[i] = look{l.ID, l.Name, l.Since, l.Tagline, l.Hero}
	}
	var b bytes.Buffer
	fmt.Fprintf(&b, "# %s\n\n", Generated)
	if err := toml.NewEncoder(&b).Encode(map[string]any{"looks": out}); err != nil {
		return nil, err
	}
	return b.Bytes(), nil
}

// The GUI README's section on the looks is between these lines.
const (
	ReadmeBegin = "<!-- looks: " + Generated + " -->"
	ReadmeEnd   = "<!-- end looks -->"
)

// Readme returns the GUI README, readme, with its section on the looks
// made again from all.
func Readme(readme []byte, all []Look) ([]byte, error) {
	src := string(readme)
	// The begin line is found by its start, so a change to its words
	// doesn't lose the section.
	begin := strings.Index(src, "<!-- looks: ")
	end := strings.Index(src, ReadmeEnd)
	if begin < 0 || end < begin {
		return nil, errors.New("the README has no looks section; it goes between " + ReadmeBegin + " and " + ReadmeEnd)
	}
	var b strings.Builder
	b.WriteString(src[:begin])
	b.WriteString(ReadmeBegin + "\n")
	for _, l := range all {
		fmt.Fprintf(&b, "\n**%s**, since %s. %s\n", l.Name, l.Since, l.Description)
		for _, s := range l.Screenshots {
			fmt.Fprintf(&b, "\n![%s](../../site/static/images/gui/%s)\n", s.Alt, s.File)
		}
	}
	b.WriteString("\n" + src[end:])
	return []byte(b.String()), nil
}
