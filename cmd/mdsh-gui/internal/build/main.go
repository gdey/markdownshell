// Command build bundles the frontend's TypeScript into frontend/bundle with
// esbuild, without npm. go generate runs it after regenerating the
// bindings:
//
//	go generate
//
// Imports of CodeMirror and xterm packages become imports of the vendored
// bundles, frontend/vendor/codemirror.js and xterm.js, which the app
// serves beside the bundle, and
// /wails/runtime.js stays an import, since Wails serves it.
package main

import (
	"errors"
	"log"
	"os"

	"github.com/evanw/esbuild/pkg/api"
)

// vendored are the packages that frontend/vendor/codemirror.js holds, and
// xterm those that frontend/vendor/xterm.js holds.
const (
	vendored = `^(@codemirror/.*|@replit/codemirror-vim|@lezer/highlight)$`
	xterm    = `^@xterm/`
)

func main() {
	log.SetFlags(0)
	if err := build(); err != nil {
		log.Fatal("build: ", err)
	}
}

func build() error {
	if err := os.RemoveAll("frontend/bundle"); err != nil {
		return err
	}
	res := api.Build(api.BuildOptions{
		EntryPoints: []string{"frontend/src/app.ts", "frontend/src/settings.ts"},
		Outdir:      "frontend/bundle",
		Bundle:      true,
		Splitting:   true,
		Format:      api.FormatESModule,
		Target:      api.ES2022,
		Sourcemap:   api.SourceMapNone,
		// The bundle is generated; the source is in frontend/src.
		MinifyWhitespace:  true,
		MinifySyntax:      true,
		MinifyIdentifiers: true,
		LegalComments:     api.LegalCommentsEndOfFile,
		External:          []string{"/wails/runtime.js"},
		Banner:            map[string]string{"js": "// Generated by go generate from frontend/src. DO NOT EDIT."},
		ChunkNames:        "[name]",
		Plugins: []api.Plugin{{
			Name: "vendored",
			Setup: func(b api.PluginBuild) {
				b.OnResolve(api.OnResolveOptions{Filter: vendored}, func(api.OnResolveArgs) (api.OnResolveResult, error) {
					return api.OnResolveResult{Path: "../vendor/codemirror.js", External: true}, nil
				})
				b.OnResolve(api.OnResolveOptions{Filter: xterm}, func(api.OnResolveArgs) (api.OnResolveResult, error) {
					return api.OnResolveResult{Path: "../vendor/xterm.js", External: true}, nil
				})
			},
		}},
		Write:    true,
		LogLevel: api.LogLevelWarning,
	})
	if len(res.Errors) > 0 {
		return errors.New("esbuild failed")
	}
	return nil
}
