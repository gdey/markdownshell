// Command build bundles the frontend's TypeScript into frontend/bundle with
// esbuild, without npm, and makes what names the looks from their
// folders in frontend/looks (see package looks): frontend/src/looks.gen.ts,
// frontend/bundle/looks.css, the website's site/data/looks.toml and the
// GUI README's section on them. go generate runs it after regenerating
// the bindings:
//
//	go generate
//
// Imports of CodeMirror and xterm packages become imports of the vendored
// bundles, frontend/vendor/codemirror.js and xterm.js, which the app
// serves beside the bundle, and
// /wails/runtime.js stays an import, since Wails serves it.
package main

import (
	"errors"
	"fmt"
	"log"
	"os"
	"strings"

	"github.com/evanw/esbuild/pkg/api"
	"github.com/gdey/markdownshell/cmd/mdsh-gui/looks"
)

// vendored are the packages that frontend/vendor/codemirror.js holds, and
// xterm those that frontend/vendor/xterm.js holds.
const (
	vendored = `^(@codemirror/.*|@replit/codemirror-vim|@lezer/highlight)$`
	xterm    = `^@xterm/`
)

func main() {
	log.SetFlags(0)
	if err := build(); err != nil {
		log.Fatal("build: ", err)
	}
}

func build() error {
	all, err := looks.Load(os.DirFS("frontend/looks"))
	if err != nil {
		return err
	}
	if err := writeLooks(all); err != nil {
		return err
	}
	if err := os.RemoveAll("frontend/bundle"); err != nil {
		return err
	}
	opts := api.BuildOptions{
		EntryPoints: []string{"frontend/src/app.ts", "frontend/src/settings.ts", "frontend/src/window.ts"},
		Outdir:      "frontend/bundle",
		Bundle:      true,
		Splitting:   true,
		Format:      api.FormatESModule,
		Target:      api.ES2022,
		Sourcemap:   api.SourceMapNone,
		// The bundle is generated; the source is in frontend/src.
		MinifyWhitespace:  true,
		MinifySyntax:      true,
		MinifyIdentifiers: true,
		LegalComments:     api.LegalCommentsEndOfFile,
		External:          []string{"/wails/runtime.js"},
		Banner:            map[string]string{"js": "// Generated by go generate from frontend/src. DO NOT EDIT."},
		// Code that two entries share goes in a chunk of its own, named
		// for its content, since entries can share different code.
		ChunkNames: "[name]-[hash]",
		Plugins: []api.Plugin{{
			Name: "vendored",
			Setup: func(b api.PluginBuild) {
				b.OnResolve(api.OnResolveOptions{Filter: vendored}, func(api.OnResolveArgs) (api.OnResolveResult, error) {
					return api.OnResolveResult{Path: "../vendor/codemirror.js", External: true}, nil
				})
				b.OnResolve(api.OnResolveOptions{Filter: xterm}, func(api.OnResolveArgs) (api.OnResolveResult, error) {
					return api.OnResolveResult{Path: "../vendor/xterm.js", External: true}, nil
				})
			},
		}},
		Write:    true,
		LogLevel: api.LogLevelWarning,
	}
	if res := api.Build(opts); len(res.Errors) > 0 {
		return errors.New("esbuild failed")
	}
	// The changelog and cheat sheet pages are bundled whole, on their
	// own: splitting them with the others would split their shared
	// chunk in two.
	opts.EntryPoints = []string{"frontend/src/changelog.ts", "frontend/src/cheatsheet.ts"}
	opts.Splitting = false
	if res := api.Build(opts); len(res.Errors) > 0 {
		return errors.New("esbuild failed")
	}
	return bundleLooks(all)
}

// writeLooks writes the files made from the looks' manifests.
func writeLooks(all []looks.Look) error {
	ts, err := looks.TS(all)
	if err != nil {
		return err
	}
	site, err := looks.SiteData(all)
	if err != nil {
		return err
	}
	readme, err := os.ReadFile("README.md")
	if err != nil {
		return err
	}
	if readme, err = looks.Readme(readme, all); err != nil {
		return err
	}
	if err := os.MkdirAll("../../site/data", 0o755); err != nil {
		return err
	}
	for name, b := range map[string][]byte{
		"frontend/src/looks.gen.ts":  ts,
		"../../site/data/looks.toml": site,
		"README.md":                  readme,
	} {
		if err := os.WriteFile(name, b, 0o644); err != nil {
			return err
		}
	}
	return nil
}

// bundleLooks bundles every look's look.css, in the looks' order, into
// frontend/bundle/looks.css, the one stylesheet for the looks that the
// pages load after style.css.
func bundleLooks(all []looks.Look) error {
	var imports strings.Builder
	for _, l := range all {
		if l.ID != "" {
			fmt.Fprintf(&imports, "@import \"./%s/look.css\";\n", l.Dir)
		}
	}
	res := api.Build(api.BuildOptions{
		Stdin: &api.StdinOptions{
			Contents:   imports.String(),
			ResolveDir: "frontend/looks",
			Sourcefile: "looks.css",
			Loader:     api.LoaderCSS,
		},
		Outfile:  "frontend/bundle/looks.css",
		Bundle:   true,
		Banner:   map[string]string{"css": "/* " + looks.Generated + " */"},
		Write:    true,
		LogLevel: api.LogLevelWarning,
	})
	if len(res.Errors) > 0 {
		return errors.New("esbuild failed on the looks")
	}
	return nil
}
