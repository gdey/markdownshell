// Command vendorjs rebuilds the JavaScript bundles mdsh-gui vendors,
// frontend/vendor/codemirror.js and frontend/vendor/xterm.js, without npm.
// It downloads the exact package versions frontend/vendor/package-lock.json
// pins from the npm registry, checks each against the lock's integrity
// hash, bundles each entry file with esbuild, copies xterm's stylesheet
// to frontend/vendor/xterm.css, and copies the packages' type
// declarations to frontend/vendor/types for tsc and their licenses to
// frontend/vendor/licenses.
//
// Run it from cmd/mdsh-gui when the lock changes:
//
//	go run ./internal/vendorjs
//
// To move to newer versions, edit vendor/package.json and refresh the lock
// with npm install --package-lock-only, then run this again.
package main

import (
	"archive/tar"
	"bytes"
	"compress/gzip"
	"crypto/sha512"
	"encoding/base64"
	"encoding/json"
	"fmt"
	"io"
	"log"
	"net/http"
	"os"
	"path"
	"path/filepath"
	"slices"
	"strings"

	"github.com/evanw/esbuild/pkg/api"
)

const vendor = "frontend/vendor"

// typesOnly are packages whose code the webview already has; only their
// types are vendored.
var typesOnly = map[string]bool{"@wailsio/runtime": true}

// keepTypes limits which declarations of a package are copied, for
// packages with many modules the frontend doesn't use.
var keepTypes = map[string]func(string) bool{
	"@codemirror/legacy-modes": func(p string) bool {
		mode, ok := strings.CutPrefix(p, "mode/")
		return ok && slices.Contains(legacyModes, strings.Split(mode, ".")[0])
	},
}

// legacyModes are the modules of @codemirror/legacy-modes entry.js
// exports, for highlighting code blocks.
var legacyModes = []string{"shell", "go", "python", "javascript", "yaml", "toml", "rust", "ruby", "lua", "perl", "swift", "sql", "diff", "dockerfile", "properties", "css", "clike"}

// bundles are the entry files in frontend/vendor and the bundles made
// from them there.
var bundles = []struct{ entry, out string }{
	{"entry.js", "codemirror.js"},
	{"xterm-entry.js", "xterm.js"},
}

// styles are stylesheets copied from the packages, by package path, to
// frontend/vendor.
var styles = map[string]string{"@xterm/xterm/css/xterm.css": "xterm.css"}

type lock struct {
	Packages map[string]struct {
		Version   string `json:"version"`
		Resolved  string `json:"resolved"`
		Integrity string `json:"integrity"`
	} `json:"packages"`
}

func main() {
	log.SetFlags(0)
	if err := vendorJS(); err != nil {
		log.Fatal("vendorjs: ", err)
	}
}

func vendorJS() error {
	src, err := os.ReadFile(filepath.Join(vendor, "package-lock.json"))
	if err != nil {
		return err
	}
	var l lock
	if err := json.Unmarshal(src, &l); err != nil {
		return err
	}
	tmp, err := os.MkdirTemp("", "vendorjs")
	if err != nil {
		return err
	}
	defer os.RemoveAll(tmp)
	modules := filepath.Join(tmp, "node_modules")
	types := filepath.Join(vendor, "types")
	for _, dir := range []string{types, filepath.Join(vendor, "licenses")} {
		if err := os.RemoveAll(dir); err != nil {
			return err
		}
	}
	var names []string
	for key := range l.Packages {
		if name, ok := strings.CutPrefix(key, "node_modules/"); ok && !strings.Contains(name, "/node_modules/") {
			names = append(names, name)
		}
	}
	slices.Sort(names)
	for _, name := range names {
		p := l.Packages["node_modules/"+name]
		log.Printf("%s@%s", name, p.Version)
		if err := fetch(p.Resolved, p.Integrity, filepath.Join(modules, name)); err != nil {
			return fmt.Errorf("%s: %w", name, err)
		}
		if err := copyTypes(name, filepath.Join(modules, name), filepath.Join(types, name)); err != nil {
			return fmt.Errorf("%s: %w", name, err)
		}
	}
	for from, to := range styles {
		if err := copyFile(filepath.Join(modules, filepath.FromSlash(from)), filepath.Join(vendor, to)); err != nil {
			return err
		}
	}
	for _, b := range bundles {
		if err := bundle(modules, b.entry, b.out); err != nil {
			return err
		}
	}
	return nil
}

// bundle bundles entry into out, both in frontend/vendor.
func bundle(modules, entry, out string) error {
	if err := checkExports(modules, entry); err != nil {
		return err
	}
	res := api.Build(api.BuildOptions{
		EntryPoints:       []string{filepath.Join(vendor, entry)},
		Outfile:           filepath.Join(vendor, out),
		Bundle:            true,
		Format:            api.FormatESModule,
		Target:            api.ES2022,
		MinifyWhitespace:  true,
		MinifySyntax:      true,
		MinifyIdentifiers: true,
		LegalComments:     api.LegalCommentsEndOfFile,
		NodePaths:         []string{modules},
		Banner:            map[string]string{"js": "// Generated by go run ./internal/vendorjs from package-lock.json. DO NOT EDIT."},
		Write:             true,
		LogLevel:          api.LogLevelWarning,
	})
	if len(res.Errors) > 0 {
		return fmt.Errorf("%s: esbuild failed", entry)
	}
	return nil
}

// fetch downloads a package tarball, checks its integrity and unpacks
// it into dir.
func fetch(url, integrity, dir string) error {
	algo, want, ok := strings.Cut(integrity, "-")
	if !ok || algo != "sha512" {
		return fmt.Errorf("integrity %q is not sha512", integrity)
	}
	resp, err := http.Get(url)
	if err != nil {
		return err
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		return fmt.Errorf("%s: %s", url, resp.Status)
	}
	data, err := io.ReadAll(resp.Body)
	if err != nil {
		return err
	}
	sum := sha512.Sum512(data)
	if got := base64.StdEncoding.EncodeToString(sum[:]); got != want {
		return fmt.Errorf("%s: integrity mismatch", url)
	}
	gz, err := gzip.NewReader(bytes.NewReader(data))
	if err != nil {
		return err
	}
	tr := tar.NewReader(gz)
	for {
		h, err := tr.Next()
		if err == io.EOF {
			return nil
		}
		if err != nil {
			return err
		}
		if h.Typeflag != tar.TypeReg {
			continue
		}
		// Tarballs hold package/…; some use another top folder.
		_, rel, ok := strings.Cut(path.Clean(h.Name), "/")
		if !ok || !filepath.IsLocal(rel) {
			continue
		}
		out := filepath.Join(dir, filepath.FromSlash(rel))
		if err := os.MkdirAll(filepath.Dir(out), 0o755); err != nil {
			return err
		}
		f, err := os.Create(out)
		if err != nil {
			return err
		}
		_, err = io.Copy(f, tr)
		if cerr := f.Close(); err == nil {
			err = cerr
		}
		if err != nil {
			return err
		}
	}
}

// copyTypes copies a package's package.json and .d.ts files.
func copyTypes(name, from, to string) error {
	keep := keepTypes[name]
	return filepath.WalkDir(from, func(p string, d os.DirEntry, err error) error {
		if err != nil || d.IsDir() {
			return err
		}
		rel, _ := filepath.Rel(from, p)
		rel = filepath.ToSlash(rel)
		if l := strings.ToUpper(rel); l == "LICENSE" || l == "LICENSE.MD" || l == "LICENSE.TXT" {
			return copyFile(p, filepath.Join(vendor, "licenses", strings.ReplaceAll(name, "/", "__")+".txt"))
		}
		isTypes := strings.HasSuffix(rel, ".d.ts") || strings.HasSuffix(rel, ".d.mts") || strings.HasSuffix(rel, ".d.cts")
		if rel != "package.json" && (!isTypes || keep != nil && !keep(rel)) {
			return nil
		}
		return copyFile(p, filepath.Join(to, filepath.FromSlash(rel)))
	})
}

func copyFile(from, to string) error {
	data, err := os.ReadFile(from)
	if err != nil {
		return err
	}
	if err := os.MkdirAll(filepath.Dir(to), 0o755); err != nil {
		return err
	}
	return os.WriteFile(to, data, 0o644)
}

// checkExports fails if two packages that entry re-exports with export
// * share a name, since such a name would silently be dropped.
func checkExports(modules, entry string) error {
	src, err := os.ReadFile(filepath.Join(vendor, entry))
	if err != nil {
		return err
	}
	owner := map[string]string{}
	for _, line := range strings.Split(string(src), "\n") {
		pkg, ok := strings.CutPrefix(line, `export * from "`)
		if !ok {
			continue
		}
		pkg = strings.TrimSuffix(pkg, `";`)
		if typesOnly[pkg] {
			return fmt.Errorf("%s bundles %s, which is types only", entry, pkg)
		}
		res := api.Build(api.BuildOptions{
			Stdin:     &api.StdinOptions{Contents: `export * from "` + pkg + `"`, ResolveDir: modules},
			Bundle:    true,
			Format:    api.FormatESModule,
			Metafile:  true,
			NodePaths: []string{modules},
			Outdir:    "out",
			LogLevel:  api.LogLevelError,
		})
		if len(res.Errors) > 0 {
			return fmt.Errorf("%s: esbuild failed", pkg)
		}
		var meta struct {
			Outputs map[string]struct {
				Exports []string `json:"exports"`
			} `json:"outputs"`
		}
		if err := json.Unmarshal([]byte(res.Metafile), &meta); err != nil {
			return err
		}
		for _, out := range meta.Outputs {
			for _, name := range out.Exports {
				if prev, ok := owner[name]; ok && prev != pkg {
					return fmt.Errorf("%s and %s both export %s", prev, pkg, name)
				}
				owner[name] = pkg
			}
		}
	}
	return nil
}
